package com.soodfolio.api.dto;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.Valid;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotEmpty;
import jakarta.validation.constraints.Size;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.time.LocalDateTime;
import java.util.List;
import java.util.Map;
import java.util.UUID;

public class ShareLinkDtos {

    @Data
    @Builder
    @NoArgsConstructor
    @AllArgsConstructor
    public static class CreateShareLinkRequest {
        @NotBlank(message = "Company name cannot be blank")
        @Size(max = 150, message = "Company name must not exceed 150 characters")
        @Schema(description = "Target company or role name", example = "Shopee - Senior Backend Role")
        private String companyName;

        @Size(max = 100, message = "Slug alias must not exceed 100 characters")
        @Schema(description = "Optional custom human-readable alias", example = "shopee-backend")
        private String slugAlias;

        @Builder.Default
        @Schema(description = "Default display template", example = "CINEMATIC_DECK")
        private String customLayout = "CINEMATIC_DECK";

        @Schema(description = "List of allowed project/slide IDs (null or empty = allow all)")
        private List<String> allowedSlideIds;

        @Schema(description = "Link expiration timestamp (null = never expires)")
        private LocalDateTime expiresAt;

        @Schema(description = "Maximum allowed views (null = unlimited)")
        private Integer maxViews;
    }

    @Data
    @Builder
    @NoArgsConstructor
    @AllArgsConstructor
    public static class ShareLinkResponse {
        private UUID id;
        private String companyName;
        private String slugAlias;
        private String customLayout;
        private List<String> allowedSlideIds;
        private LocalDateTime expiresAt;
        private Integer maxViews;
        private int viewCount;
        private boolean isRevoked;
        private LocalDateTime createdAt;
        private String rawToken;
        private String shareUrl;
    }

    @Data
    @Builder
    @NoArgsConstructor
    @AllArgsConstructor
    public static class ShareLinkSummaryResponse {
        private UUID id;
        private String companyName;
        private String slugAlias;
        private String customLayout;
        private List<String> allowedSlideIds;
        private LocalDateTime expiresAt;
        private Integer maxViews;
        private int viewCount;
        private boolean isRevoked;
        private LocalDateTime createdAt;
    }

    @Data
    @Builder
    @NoArgsConstructor
    @AllArgsConstructor
    public static class TelemetryBatchRequest {
        @NotBlank(message = "Session ID cannot be blank")
        @Size(max = 64, message = "Session ID must not exceed 64 characters")
        @Schema(description = "Anonymous session UUID/fingerprint generated by client", example = "sess_9f81c9a1")
        private String sessionId;

        @NotEmpty(message = "Events list cannot be empty")
        @Size(max = 50, message = "Maximum 50 telemetry events allowed per batch")
        @Valid
        private List<TelemetryEventDto> events;
    }

    @Data
    @Builder
    @NoArgsConstructor
    @AllArgsConstructor
    public static class TelemetryEventDto {
        @NotBlank(message = "Slide key cannot be blank")
        @Size(max = 100, message = "Slide key must not exceed 100 characters")
        @Schema(description = "Slide key, e.g. hero, experience, project-{uuid}, education", example = "project-e5b17df0-fca2-488b-a45e-4bb5ea411a7f")
        private String slideKey;

        @Schema(description = "Seconds spent dwelling on this slide", example = "25")
        private int dwellSeconds;

        @Size(max = 20, message = "Device type must not exceed 20 characters")
        @Schema(description = "Viewer device category: DESKTOP, TABLET, MOBILE", example = "DESKTOP")
        private String deviceType;

        @Schema(description = "Viewer browser user agent (optional)")
        private String userAgent;
    }

    @Data
    @Builder
    @NoArgsConstructor
    @AllArgsConstructor
    public static class SlideTelemetryStatDto {
        private String slideKey;
        private long totalDwellSeconds;
        private long viewCount;
        private double avgDwellSeconds;
    }

    @Data
    @Builder
    @NoArgsConstructor
    @AllArgsConstructor
    public static class TelemetryAnalyticsResponse {
        private UUID shareLinkId;
        private String companyName;
        private int totalViews;
        private long totalDwellSeconds;
        private LocalDateTime lastViewedAt;
        private List<SlideTelemetryStatDto> slideStats;
        private Map<String, Long> deviceBreakdown;
    }

    @Data
    @Builder
    @NoArgsConstructor
    @AllArgsConstructor
    public static class PublicDeckResponse {
        private String companyName;
        private String customLayout;
        private int snapshotVersion;
        private PortfolioResponseDto portfolio;
    }
}
